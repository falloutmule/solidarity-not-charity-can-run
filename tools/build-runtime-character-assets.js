#!/usr/bin/env node
'use strict';

/* Deterministic compiler: transparent candidate PNGs -> one runtime registry module. */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'authoring', 'characters', 'character-isolation-v1.json');
const outputPath = path.join(root, 'src', 'imported-handoff-assets', 'runtime-character-gallery-assets.js');

function sha256(value){ return crypto.createHash('sha256').update(value).digest('hex'); }
function pngSize(bytes){
  if(bytes.toString('ascii', 1, 4) !== 'PNG') throw new Error('runtime asset is not a PNG');
  return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
}
function build(){
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if(manifest.schema !== 'snc-character-isolation-v1') throw new Error('unexpected character isolation schema');
  const seenIds = new Set(), seenPayloads = new Set();
  const records = manifest.assets.filter(asset => asset.status === 'candidate').map(asset => {
    if(!asset.runtimePath || !asset.runtimeSha256) throw new Error(asset.assetId + ': runtime output is not recorded');
    if(seenIds.has(asset.assetId)) throw new Error('duplicate asset ID: ' + asset.assetId);
    seenIds.add(asset.assetId);
    const bytes = fs.readFileSync(path.join(root, asset.runtimePath));
    const actualHash = sha256(bytes);
    if(actualHash !== asset.runtimeSha256) throw new Error(asset.assetId + ': runtime output hash drift');
    if(seenPayloads.has(actualHash)) throw new Error(asset.assetId + ': duplicate runtime image payload');
    seenPayloads.add(actualHash);
    const size = pngSize(bytes);
    if(!asset.runtimeSize || asset.runtimeSize.width !== size.width || asset.runtimeSize.height !== size.height){
      throw new Error(asset.assetId + ': runtime dimensions drift');
    }
    const group = asset.assetId.includes('_volunteer_') ? 'volunteer' : asset.assetId.includes('_civilian_') ? 'civilian' : 'household';
    return {
      id: asset.assetId,
      kind: 'npc', group, renderMode: 'billboard-single', approvalStatus: 'candidate',
      sourceRef: asset.source + ':' + asset.bounds.join(','),
      anchor: { x: asset.anchor[0], y: asset.anchor[1] },
      alphaBounds: asset.runtimeAlphaBounds,
      width: size.width, height: size.height, sha256: actualHash,
      dataUri: 'data:image/png;base64,' + bytes.toString('base64')
    };
  }).sort((a, b) => a.id.localeCompare(b.id));
  const moduleText = [
    '/* GENERATED by tools/build-runtime-character-assets.js; source: authoring/characters/character-isolation-v1.json. DO NOT EDIT. */',
    '(function(root){',
    "  'use strict';",
    '  const entries = ' + JSON.stringify(records, null, 2) + ';',
    '  const registry = root.SNC_RUNTIME_ASSET_REGISTRY || Object.create(null);',
    '  for(const entry of entries){',
    '    if(registry[entry.id]) throw new Error("duplicate SNC runtime asset: " + entry.id);',
    '    const image = new Image();',
    '    image.decoding = "async";',
    '    image.src = entry.dataUri;',
    '    image.__sncAssetId = entry.id;',
    '    image.__sncFootY = entry.height;',
    '    registry[entry.id] = Object.freeze(Object.assign({}, entry, { image }));',
    '  }',
    '  root.SNC_RUNTIME_ASSET_REGISTRY = Object.freeze(registry);',
    '})(globalThis);',
    ''
  ].join('\n');
  return { moduleText, records };
}
function main(){
  const check = process.argv.includes('--check');
  const write = process.argv.includes('--write') || !check;
  const result = build();
  if(check){
    if(!fs.existsSync(outputPath)) throw new Error('missing generated runtime registry');
    if(fs.readFileSync(outputPath, 'utf8') !== result.moduleText) throw new Error('generated runtime registry drift; run with --write');
  }
  if(write) fs.writeFileSync(outputPath, result.moduleText, 'utf8');
  console.log(JSON.stringify({ pass: true, assets: result.records.length, uniquePayloads: result.records.length, output: path.relative(root, outputPath) }, null, 2));
}
try { main(); } catch(error) { console.error('runtime-character-assets:', error.message); process.exitCode = 1; }
